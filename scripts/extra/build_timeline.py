# -*- coding: utf-8 -*-
"""Build src/timeline.js and timeline.json (single source of truth for sync)."""
import json, os

WORK = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
segs = json.load(open(os.path.join(WORK, "tts", "durations.json"), encoding="utf-8"))

LEAD, TAIL, LAST_TAIL = 0.30, 0.36, 1.20
FPS = 30
items, t = [], 0.0
for i, s in enumerate(segs):
    speech = s["dur"]
    tail = LAST_TAIL if i == len(segs) - 1 else TAIL
    dur = LEAD + speech + tail
    items.append({"id": s["id"], "text": s["text"], "start": round(t, 3),
                  "dur": round(dur, 3), "speechStart": round(t + LEAD, 3),
                  "speechDur": round(speech, 3)})
    t += dur

frames = round(t * FPS)
total = frames / FPS
data = {"fps": FPS, "frames": frames, "total": round(total, 4), "scenes": items}
print("total %.3fs -> %d frames" % (total, frames))

js = ["// generated by scripts/build_timeline.py", "const FPS = %d;" % FPS,
      "const TOTAL = %r;" % total, "const TIMELINE = [",
      ",\n".join("  " + json.dumps(x, ensure_ascii=False) for x in items), "];", ""]
open(os.path.join(WORK, "src", "timeline.js"), "w", encoding="utf-8").write("\n".join(js))
json.dump(data, open(os.path.join(WORK, "timeline.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=2)
print("wrote src/timeline.js + timeline.json")
